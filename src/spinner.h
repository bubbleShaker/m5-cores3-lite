#pragma once

#include <cstdint>  // SpinnerZone の基底型 uint8_t

// ハンドスピナーの純粋回転物理（Issue #243）。
// M5Unified・millis()・描画には一切依存しない。「本体の角速度」「指がどこに触れているか」
// 「経過時間」だけを受け取り、画面内スピナーの角度・角速度を進める。
// squeeze.h / pacman.h と同じ思想で、調整点の多い物理（摩擦・ブレーキの効き）を
// PC 上の native テストで詰められるようにする。
//
// ■ 回転の向き
//   angle / omega は **画面上で時計回りを正**とする（度・deg/s）。
//   描画側は angle をそのままローブの角度に足せばよい。
//
// ■ 入力の約束（ここが実機との境界）
//   SpinnerInput::omega_dev は「本体が画面法線まわりに回る角速度」を、
//   **画面上の時計回りを正**に揃えた値で渡す。ジャイロの生値ではない。
//   軸の割り当てと符号は基板の向き・setRotation() で変わり、この層で吸収すると
//   嘘になるため、符号合わせは呼び出し側（main.cpp）の責務とする。
//
// ■ モデル（1状態）
//   状態は「画面上の見かけ角速度 omega」1本だけ。絶対角速度と本体角速度を別々に持つ
//   厳密な剛体モデルも検討したが、弾いた後の余韻がカップリング係数任せになり体感を
//   詰めにくい。ここでは次の3つの規則だけで実物の手触りを作る:
//     1. ハブを押さえていて、かつ本体が実際に回っている間だけ、本体の回転がスピナーに伝わる
//     2. それ以外では omega はそのまま残り、軸受け摩擦で緩やかに減衰する（＝慣性）
//     3. スピン部を押さえている間は強い減衰で止まる（＝ブレーキ）
//   規則1の「本体が実際に回っている間だけ」が肝。単純に本体の角速度へ漸近させると、
//   弾き終わって本体が止まった瞬間にスピナーまで止まり、慣性が出なくなる。

// ───────── 物理定数（実機で体感を詰める時はここを触る） ─────────

// 画面上の角速度の上限(deg/s)。2880 = 8回転/秒。これを超えるとローブが視認できず、
// 1フレーム(33ms)あたり95度も進むため回転方向が逆に見え始める（時間的エイリアシング）。
constexpr float kSpMaxOmega = 2880.0f;

// ハブを押さえた時、本体の回転がスピナーへ伝わる速さ(1/s)。
// 25.0 は時定数 40ms ≒ 1フレーム強で追従する＝「連動して回る」体感。
constexpr float kSpCouple = 25.0f;
// 本体の回転がスピナーの角速度に化ける倍率。1.0 で「本体と同じ速さで回る」。
constexpr float kSpDriveGain = 1.0f;
// カップリングを効かせる本体角速度の下限(deg/s)。
// これが無いと、押さえたまま本体を静止させた時に目標 0 へ引かれてスピナーまで止まり、
// 慣性が出ない。手ブレ（数十 deg/s）では超えず、意図して回せば確実に超える値。
constexpr float kSpDriveMin = 60.0f;

// 軸受け摩擦(1/s)。0.22 なら 1/e まで約4.5秒、実用上は 20〜30秒回り続ける。
// 「回っている間に触って止める」遊びが成立する長さとして選んだ。
constexpr float kSpFriction = 0.22f;
// ブレーキの減衰(1/s)。25.0 で約0.12秒あれば体感上は停止する。
// 完全に即時停止(omega=0)にしないのは、指を当てた瞬間の「キュッ」と減速する感触を残すため。
constexpr float kSpBrakeDamp = 25.0f;
// これ未満の角速度は 0 に丸めて完全停止させる(deg/s)。
// 指数減衰は 0 へ漸近するだけで到達しないため、終わりを作るのに要る。
// 8 deg/s は 45秒で1回転＝止まって見える速さ。
constexpr float kSpStopEps = 8.0f;

// 1フレームで進める時間の上限(秒)。描画が詰まって dt が跳ねた時に、角度が飛んで
// 回転方向が破綻するのを防ぐ（squeeze の kSqMaxDt と同じ役目）。
constexpr float kSpMaxDt = 0.05f;

// ───────── 触れた場所の区分 ─────────
// 指がどこに乗っているかは中心からの相対座標だけで決まる純粋な判定なので、実機層ではなく
// ここに置く。ハブとスピン部の境界は体感を直接左右する調整点であり、native テストで
// 押さえておきたいため（描画半径ではなく「指の接地面」に合わせた値なので描画側とは別物）。

// タッチ判定の半径(px)。描画半径より少し大きく取る（指の接地面は点ではないため）。
constexpr float kSpHubTouchR  = 40.0f;   // これ以内＝ハブを押さえた（＝軸を持った）
constexpr float kSpBodyTouchR = 108.0f;  // ハブ外〜これ以内＝スピン部（＝ブレーキ）

enum class SpinnerZone : uint8_t {
    Hub,      // 中央ハブ＝軸を持つ
    Body,     // スピン部（ローブ）＝ブレーキ
    Outside,  // スピナーの外＝シーンは反応しない（長押しはメニューへ通す）
};

// スピナー中心からの相対座標(px)がどの区分に入るかを返す純粋関数。
// 非有限値(NaN/Inf)は Outside として扱う（誤って軸を持った扱いにしない安全側）。
SpinnerZone spinner_zone(float dx, float dy);

// ───────── 状態と入出力 ─────────

// スピナーの状態。呼び出し側が1個保持して毎フレーム spinner_update に渡す。
struct SpinnerState {
    float angle = 0.0f;  // 画面上の回転角(度)。常に [0, 360) に正規化されている
    float omega = 0.0f;  // 画面上の角速度(deg/s)。時計回りが正
    // 累計回転数。「何回まわしたか」を出すための表示専用の値で、物理には影響しない。
    // 逆回転でも減らさない（回した仕事量として積む）。
    float turns = 0.0f;
    // 直近で叩き出した最高角速度(deg/s)。turns と同じく表示専用。
    // 完全停止した時だけ 0 に戻すので、1回の回しのベストが読み取れる。
    float peak_omega = 0.0f;
};

// 1フレーム分の入力。
struct SpinnerInput {
    // 本体の角速度(deg/s・画面上の時計回りが正)。ジャイロ生値ではない（上の約束を参照）。
    float omega_dev = 0.0f;
    bool  held      = false;  // 中央ハブを押さえているか（＝軸を持っているか）
    bool  braking   = false;  // スピン部を押さえているか（＝ブレーキ）
    float dt        = 0.0f;   // 前フレームからの経過秒
};

// 角度・角速度・表示用の集計をすべて初期化する。
void spinner_reset(SpinnerState& s);

// 物理を dt だけ進める。dt は内部で [0, kSpMaxDt] にクランプされる（負値も 0 に丸まる）。
// 入力に非有限値(NaN/Inf)が混じったフレームは丸ごと捨て、状態を汚さない。
// 呼び出し後、angle は必ず [0, 360)、|omega| は必ず kSpMaxOmega 以下（不変条件）。
// braking は held より優先する（両方の指が乗っていてもブレーキが勝つ）。
void spinner_update(SpinnerState& s, const SpinnerInput& in);

// 表示用: 現在の回転数(rpm)。向きは問わないので常に 0 以上。
float spinner_rpm(const SpinnerState& s);
