#pragma once
#include <stdint.h>

// 曲選択画面の背景に敷く「動くフラクタル幾何学模様」の純粋ロジック（Issue #199）。
// 実描画・実データに依存しない算術だけをここに置き、native テストする
// （video.h の video_bg_tone / video_bg_lerp と同じ流儀）。
//
// 模様の正体は XOR（マンチング・スクエア）: (x ^ y) の各ビット面はシェルピンスキー三角形
// ＝自己相似（フラクタル）の入れ子になる。座標を時間でドリフトさせると入れ子構造が
// 組み替わり続け、整数演算だけで「動く幾何学模様」が得られる（毎フレーム全画面を
// 計算し直しても ESP32 で間に合う軽さがこの方式を選んだ理由。sin 場のプラズマは
// 有機的すぎて「幾何学的」の要求に合わないため不採用）。

// フレーム不変量（座標ドリフト量とパレット位相）を t_ms から求める（reviewer 指摘）。
// これらは1コマの間ずっと同じ値なので、表示側は1コマにつき本関数を1回だけ呼び、
// 画素ごとには fractal_at を呼ぶ（毎画素の除算3回を 76,800 回繰り返さないため）。
//   t_ms は millis() をそのまま渡してよい（uint32 の全域で動作する。49.7 日ラップの
//   瞬間に模様が一度飛ぶだけで壊れはしない）。
void fractal_offsets(uint32_t t_ms, int* out_dx, int* out_dy, uint32_t* out_phase);

// ドリフト適用済み座標（x + dx0, y + dy0）と位相から強度 0..255 を返す。
//   細かい層（等倍 XOR）と粗い層（1/4 縮尺 XOR）を重ねて自己相似の奥行きを出す。
//   引数は非負を想定（fractal_offsets の出力＋画面座標なら常に非負）。
uint8_t fractal_at(int dx, int dy, uint32_t phase);

// 点 (x, y) の時刻 t_ms における強度 0..255。fractal_offsets + fractal_at の合成
// （1点だけ欲しい時・テスト用の入口。全画面を回す表示側は分割版を使う）。
uint8_t fractal_value(int x, int y, uint32_t t_ms);

// 強度 v (0..255) でトーン色 tone (0xRRGGBB) を暗→明に段階づける。
//   v=0 は黒、v=255 は tone そのもの。各成分は独立に線形スケール（単調・tone を超えない）。
//   tone の 24bit を超えるビットは無視する（video_bg_tone と同じ契約）。
//   256 段のパレット LUT を焼く時に使う（表示側は RGB565 化して毎フレーム引くだけ）。
uint32_t fractal_shade(uint32_t tone, uint8_t v);

// 強度のガンマ補正 v²/255（0..255 → 0..255・単調・両端固定）。線形のままだと中間調が
// 支配的になり模様の輪郭がぼやけるため、パレットを焼く時に暗部を締める用途で使う。
uint8_t fractal_gamma(uint8_t v);
